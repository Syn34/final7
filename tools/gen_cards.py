"""Regenerate src/cards_data.c from tools/cards.json:  python tools/gen_cards.py"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cards = json.load(open(os.path.join(ROOT, "tools", "cards.json"), encoding="utf-8"))


def cstr(s):
    s = (s or "").encode("ascii", "replace").decode()
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = ["/* GENERATED by tools/gen_cards.py from tools/cards.json - do not edit. */",
         '#include "fm.h"', "", "const Card CARDS[N_CARDS] = {"]
for c in cards:
    cost = c["cost"] if c["cost"] is not None and c["cost"] < 999999 and c["password"] else -1
    lines.append("    {%d, %s, %s, %s, %d, %d, %d, %s, %d}," % (
        c["id"], cstr(c["name"]), cstr(c["type"]), cstr(c["attr"]), c["level"] or 0, c["atk"], c["def_"],
        cstr(c["password"]), cost))
lines.append("};")
open(os.path.join(ROOT, "src", "cards_data.c"), "w", newline="\n").write("\n".join(lines) + "\n")
print(len(cards), "cards written")
