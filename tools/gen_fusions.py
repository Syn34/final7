"""Regenerate src/fusion_data.c from tools/fusions.json:  python tools/gen_fusions.py
fusions.json comes from the yfm.db catalog in vincevandriel/yfm-fusion-companion (MIT):
every fusing pair (low id, high id, result) and every equip -> monster compatibility."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(ROOT, "tools", "fusions.json")))
fus = sorted(tuple(x) for x in d["fusions"])
eq = sorted((m, e) for e, m in d["equips"])
out = ["/* GENERATED by tools/gen_fusions.py from tools/fusions.json - do not edit. */",
       '#include "sim.h"', "", f"const int N_FUSIONS = {len(fus)};",
       "const uint16_t FUSIONS[][3] = {"]
for i in range(0, len(fus), 6):
    out.append("    " + " ".join("{%d,%d,%d}," % f for f in fus[i:i + 6]))
out += ["};", "", f"const int N_EQUIPS = {len(eq)};", "const uint16_t EQUIPS[][2] = {   /* monster, equip */"]
for i in range(0, len(eq), 10):
    out.append("    " + " ".join("{%d,%d}," % e for e in eq[i:i + 10]))
out.append("};")
open(os.path.join(ROOT, "src", "fusion_data.c"), "w", newline="\n").write("\n".join(out) + "\n")
print(len(fus), "fusions,", len(eq), "equip pairs")
